/**
 * Scene templates.
 *
 * scaffold_scene used to emit a TODO comment and an empty fragment for dom-demo
 * beats, which meant the calling agent had to invent a scene from primitives for
 * every beat in the video. Building one real 20 beat video that way took over two
 * thousand lines of hand written React. Agents edit a working thing far better than
 * they compose one from nothing, so every template here renders on its own with no
 * edits, and the agent's job becomes changing content rather than building structure.
 *
 * Templates only use what `@openvidstudio/core` exports, because that is all a
 * scaffolded project has.
 *
 * Two things encoded here that are easy to get wrong and expensive to discover:
 *
 * 1. Camera scale. The visible area is the stage divided by the camera scale, so at
 *    1.4 only 1371x771 of the 1920x1080 stage is on screen. Panels built at stage
 *    size get cropped at the frame edge with no warning. Constructed scenes
 *    therefore use a gentle push (1.04 to 1.15) and keep content inside a safe box.
 *    STYLE.md's 120-250% rule is about not showing flat full screen screenshots,
 *    which is a capture-beat concern, and capture templates do use it.
 *
 * 2. Real captures get their frame size from the file on disk, not from a guess.
 */

export type SceneKind = "real-screenshot" | "real-recording" | "dom-demo" | "higgsfield-clip";

export type TemplateName =
  | "browser-capture"
  | "recording"
  | "terminal"
  | "split-panel"
  | "checklist"
  | "stat"
  | "code"
  | "comparison"
  | "cta"
  | "title";

export interface SceneContext {
  beatId: string;
  componentName: string;
  /** The beat's `visual.description`, used as on-screen copy so the first render says something. */
  description: string;
  /** The beat's narration line, used for the caption. */
  vo: string;
  durationFrames: number;
  /** For capture templates. */
  url?: string;
  captureWidth?: number;
  captureHeight?: number;
}

/** Content wider or taller than this gets cropped once the camera pushes in. */
const SAFE_W = 1560;

const HEADER = (beatId: string, template: TemplateName, direction = "") =>
  `// Scene for beat "${beatId}", generated by scaffold_scene from the "${template}" template.
//
// This renders as-is. Edit the copy and the timings; the structure, camera and
// safe-area sizing are already correct.${
    direction ? `
//
// The beat asks for: ${direction.replace(/\s+/g, " ").slice(0, 240)}` : ""
  }`;

/**
 * Heading text.
 *
 * Deliberately not `visual.description`. That field is a stage direction written for
 * whoever builds the scene ("two labelled panels built from this project's tokens"),
 * and putting it on screen reads as instructions leaking into the video. The beat id
 * is short, already names the beat's subject, and title-cases into a usable heading.
 */
function headline(ctx: SceneContext): string {
  const words = ctx.beatId.replace(/[-_]+/g, " ").trim().split(/\s+/);
  const text = words.map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(" ");
  return esc(text || "Untitled beat");
}

/** First sentence of the narration, for supporting copy under a heading. */
function leadLine(ctx: SceneContext, max = 150): string {
  const first = (ctx.vo || "").split(/(?<=[.!?])\s/)[0]?.trim() ?? "";
  const text = first || ctx.description || "";
  return esc(text.length > max ? `${text.slice(0, max - 3).trimEnd()}...` : text);
}

function esc(s: string): string {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, " ");
}

/** Caption timing: in after the opening settle, out before the cut. */
function captionWindow(frames: number): { at: number; out: number } {
  return { at: Math.round(frames * 0.18), out: Math.max(24, Math.round(frames * 0.82)) };
}

/* ------------------------------------------------------------------ capture */

function browserCapture(ctx: SceneContext): string {
  const w = ctx.captureWidth ?? 1440;
  const h = ctx.captureHeight ?? 900;
  // BrowserFrame adds a chrome bar above the page.
  const frameW = Math.min(1600, w + 80);
  const frameH = Math.round(frameW * (h / w)) + 56;
  const mid = Math.round(ctx.durationFrames * 0.55);
  const cap = captionWindow(ctx.durationFrames);
  return `${HEADER(ctx.beatId, "browser-capture", ctx.description)}
//
// Frame size comes from the real capture on disk (${w}x${h}), not a guess, so the
// page is not letterboxed or stretched. Camera sits inside the UI and keeps moving.

import React from "react";
import { Img, staticFile } from "remotion";
import { CinematicScene, Layer, BrowserFrame, Caption, E } from "@openvidstudio/core";

const FRAME_W = ${frameW};
const FRAME_H = ${frameH};
const LEFT = (1920 - FRAME_W) / 2;
const TOP = (1080 - FRAME_H) / 2;

export const ${ctx.componentName}: React.FC = () => {
  return (
    <CinematicScene
      camera={[
        { frame: 0, x: 960, y: 470, scale: 1.35, rotZ: -0.5 },
        { frame: ${mid}, x: 960, y: 560, scale: 1.62, rotZ: 0.4, easing: E.cinematic },
        { frame: ${ctx.durationFrames}, x: 985, y: 620, scale: 1.78, rotZ: 0.8, easing: E.drift },
      ]}
      overlay={<Caption text="${esc(ctx.vo).slice(0, 70)}" at={${cap.at}} out={${cap.out}} fontSize={30} />}
    >
      <Layer depth={0}>
        <div style={{ position: "absolute", left: LEFT, top: TOP }}>
          <BrowserFrame url="${esc(ctx.url ?? "localhost:3000")}" width={FRAME_W} height={FRAME_H}>
            <Img
              src={staticFile("images/${ctx.beatId}.png")}
              style={{ width: "100%", height: "100%", objectFit: "cover", objectPosition: "top" }}
            />
          </BrowserFrame>
        </div>
      </Layer>
    </CinematicScene>
  );
};
`;
}

function recording(ctx: SceneContext, higgsfield: boolean): string {
  const note = higgsfield
    ? `// The asset comes from import_higgsfield_clip. Composited as a bare Layer and
// OffthreadVideo, never a BrowserFrame: an AI generated clip must not carry the
// visual signature of real captured UI (STYLE.md's provenance rule).`
    : `// Composited as a bare Layer and OffthreadVideo, per STYLE.md's convention for
// recordings. The camera moves over the recording exactly as it would over a still.`;
  const cap = captionWindow(ctx.durationFrames);
  return `${HEADER(ctx.beatId, "recording", ctx.description)}
//
${note}

import React from "react";
import { OffthreadVideo, staticFile } from "remotion";
import { CinematicScene, Layer, Caption, E } from "@openvidstudio/core";

export const ${ctx.componentName}: React.FC = () => {
  return (
    <CinematicScene
      camera={[
        { frame: 0, x: 960, y: 520, scale: 1.28, rotZ: 0.4 },
        { frame: ${ctx.durationFrames}, x: 960, y: 560, scale: 1.5, rotZ: -0.3, easing: E.drift },
      ]}
      overlay={<Caption text="${esc(ctx.vo).slice(0, 70)}" at={${cap.at}} out={${cap.out}} fontSize={30} />}
    >
      <Layer depth={0}>
        <OffthreadVideo
          src={staticFile("video/${ctx.beatId}.mp4")}
          style={{ width: "100%", height: "100%", objectFit: "cover" }}
        />
      </Layer>
    </CinematicScene>
  );
};
`;
}

/* ------------------------------------------------------------- constructed */

const SAFE_WRAP = (inner: string) => `      <Layer depth={0}>
        <div
          style={{
            position: "absolute",
            inset: 0,
            display: "flex",
            alignItems: "center",
            justifyContent: "center",
            padding: "0 ${(1920 - SAFE_W) / 2}px",
          }}
        >
${inner}
        </div>
      </Layer>`;

const GENTLE_CAMERA = (frames: number, a = 1.04, b = 1.15) => `      camera={[
        { frame: 0, x: 960, y: 540, scale: ${a}, rotZ: -0.4 },
        { frame: ${frames}, x: 960, y: 548, scale: ${b}, rotZ: 0.35, easing: E.drift },
      ]}`;

function terminal(ctx: SceneContext): string {
  return `${HEADER(ctx.beatId, "terminal", ctx.description)}

import React from "react";
import { CinematicScene, Layer, TerminalReplay, color, E } from "@openvidstudio/core";

export const ${ctx.componentName}: React.FC = () => {
  return (
    <CinematicScene
${GENTLE_CAMERA(ctx.durationFrames, 1.05, 1.16)}
    >
${SAFE_WRAP(`          <TerminalReplay
            title="Project"
            width={1400}
            fontSize={27}
            cps={24}
            steps={[
              { type: "cmd", text: "echo replace me with the real command" },
              {
                type: "out",
                lines: [
                  { text: "replace with the real output", color: color.textSecondary },
                  { text: "done", color: color.success, glow: true },
                ],
              },
            ]}
          />`)}
    </CinematicScene>
  );
};
`;
}

