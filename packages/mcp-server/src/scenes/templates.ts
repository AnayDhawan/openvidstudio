/* -------------------------------------------------------------- selection */

const KEYWORDS: [RegExp, TemplateName][] = [
  [/\bterminal|command|shell|cli\b|npm |npx |install|clone|build\b/i, "terminal"],
  [/\bchecklist|requirement|prereq|steps?\b|tick|verify\b/i, "checklist"],
  [/\bconfig|json|code panel|snippet|mcp\.json|package\.json\b/i, "code"],
  [/\bversus|vs\.?\b|compare|comparison|two (options|panels|tiers)|either\b/i, "comparison"],
  [/\bcta|call to action|repo|github|star\b/i, "cta"],
  [/\bstat|number|percent|count|figure|\$\d/i, "stat"],
  [/\bpanel|split|beside|alongside|left|right\b/i, "split-panel"],
];

/** Pick a template from the beat's capture method and what its description talks about. */
export function pickTemplate(kind: SceneKind, description: string): TemplateName {
  if (kind === "real-screenshot") return "browser-capture";
  if (kind === "real-recording" || kind === "higgsfield-clip") return "recording";
  for (const [re, name] of KEYWORDS) {
    if (re.test(description)) return name;
  }
  return "title";
}

export function renderTemplate(
  template: TemplateName,
  ctx: SceneContext,
  kind: SceneKind,
): string {
  switch (template) {
    case "browser-capture":
      return browserCapture(ctx);
    case "recording":
      return recording(ctx, kind === "higgsfield-clip");
    case "terminal":
      return terminal(ctx);
    case "split-panel":
      return splitPanel(ctx);
    case "checklist":
      return checklist(ctx);
    case "stat":
      return stat(ctx);
    case "code":
      return code(ctx);
    case "comparison":
      return comparison(ctx);
    case "cta":
      return cta(ctx);
    case "title":
    default:
      return title(ctx);
  }
}
