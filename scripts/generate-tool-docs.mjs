#!/usr/bin/env node
// Keeps the tool list and every tool-count claim in step with what the server really registers.
//
//   node scripts/generate-tool-docs.mjs          write packages/docs/TOOLS.md and refresh the counts
//   node scripts/generate-tool-docs.mjs --check  change nothing; exit 1 if either is stale (CI)
//
// The source of truth is createMcpServer's own registry in packages/mcp-server/dist, so build
// the package first. Counts in prose sit between comment markers that this script rewrites:
//
//   <!-- tools:base -->forty<!-- /tools -->            words, lower case   (no Higgsfield tier)
//   <!-- tools:Base -->Forty<!-- /tools -->            words, capitalised
//   <!-- tools:base:digits -->40<!-- /tools -->        digits
//   <!-- tools:higgsfield -->forty-one<!-- /tools -->  the count with the Higgsfield tier on
//   (and the same :Higgsfield / :higgsfield:digits forms)
//
// Everything outside the markers is the author's own prose and is never touched.

import * as fs from "node:fs";
import * as path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const serverJs = path.join(root, "packages", "mcp-server", "dist", "server.js");
if (!fs.existsSync(serverJs)) {
  console.error(`${serverJs} not found. Build first: pnpm --filter @openvidstudio/mcp-server build`);
  process.exit(2);
}
const { createMcpServer } = require(serverJs);

const higgsfieldConfig = {
  hasHiggsfield: true,
  targetDurationSeconds: 60,
  videoConfig: { fps: 30, width: 1920, height: 1080 },
  capture: { appUrl: "http://localhost:3000", width: 1440, height: 900, settleMs: 1200 },
  narration: { engine: "edge-tts", voice: "en-US-AndrewNeural" },
};
// _registeredTools is the SDK's own runtime map; there is no public accessor for "what is registered".
const registry = (config) => createMcpServer(config)._registeredTools;
const baseTools = registry(undefined);
const allTools = registry(higgsfieldConfig);
const baseCount = Object.keys(baseTools).length;
const allCount = Object.keys(allTools).length;
const higgsfieldOnly = new Set(Object.keys(allTools).filter((n) => !(n in baseTools)));

const ONES = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen", "nineteen"];
const TENS = ["", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety"];
function words(n) {
  if (n < 20) return ONES[n];
  const t = TENS[Math.floor(n / 10)];
  return n % 10 === 0 ? t : `${t}-${ONES[n % 10]}`;
}
const capital = (s) => s[0].toUpperCase() + s.slice(1);

function render(kind) {
  const n = kind.toLowerCase().startsWith("higgsfield") ? allCount : baseCount;
  if (kind.endsWith(":digits")) return String(n);
  const w = words(n);
  return kind[0] === kind[0].toUpperCase() ? capital(w) : w;
}

/** Rewrites every <!-- tools:KIND -->...<!-- /tools --> span in `text`. */
function refreshCounts(text) {
  return text.replace(/<!-- tools:([A-Za-z:]+) -->[\s\S]*?<!-- \/tools -->/g, (_, kind) => `<!-- tools:${kind} -->${render(kind)}<!-- /tools -->`);
}

function toolsDoc() {
  const names = Object.keys(allTools).sort();
  const rows = names.map((name) => {
    const title = String(allTools[name].title ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
    const note = higgsfieldOnly.has(name) ? " Only registered when `hasHiggsfield` is true in `openvidstudio.config.json`." : "";
    return `| \`${name}\` | ${title}.${note} |`;
  });
  return [
    "# Tools",
    "",
    "GENERATED by `node scripts/generate-tool-docs.mjs` from the tools the server actually registers.",
    "Do not edit by hand: CI fails if this file is out of date. Each tool's own description (what it",
    "checks, what it returns, when to use it) is what an MCP client shows an agent; this page is the map.",
    "",
    `${baseCount} tools, ${allCount} with the Higgsfield tier enabled.`,
    "",
    "| Tool | What it does |",
    "| --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

const targets = [
  { file: "packages/docs/TOOLS.md", next: () => toolsDoc() },
  { file: "README.md", next: (current) => refreshCounts(current) },
];

let stale = 0;
for (const t of targets) {
  const abs = path.join(root, t.file);
  const current = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : "";
  const eol = current.includes("\r\n") ? "\r\n" : "\n";
  const wanted = t.next(current.replace(/\r\n/g, "\n")).replace(/\n/g, eol);
  if (wanted === current) continue;
  stale++;
  if (check) {
    console.error(`STALE ${t.file}`);
  } else {
    fs.writeFileSync(abs, wanted, "utf8");
    console.log(`wrote ${t.file}`);
  }
}

if (check) {
  if (stale > 0) {
    console.error(`\n${stale} generated file(s) are out of date with the ${baseCount}/${allCount} tools the server registers.\nRun: node scripts/generate-tool-docs.mjs   (after building mcp-server), and commit the result.`);
    process.exit(1);
  }
  console.log(`tool docs ok: ${baseCount} tools, ${allCount} with Higgsfield`);
} else if (stale === 0) {
  console.log(`already current: ${baseCount} tools, ${allCount} with Higgsfield`);
}
